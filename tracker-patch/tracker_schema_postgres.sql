-- Same schema the tracker creates automatically (PriceHistory._POSTGRES_SCHEMA_SQL).
-- Run this yourself only if you prefer to create the tables up front.

    CREATE TABLE IF NOT EXISTS runs (
        run_id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        started_at       TIMESTAMPTZ NOT NULL,
        finished_at      TIMESTAMPTZ,
        status           TEXT NOT NULL DEFAULT 'started',
        error_summary    TEXT
    );

    CREATE TABLE IF NOT EXISTS price_points (
        id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        run_id           BIGINT NOT NULL REFERENCES runs(run_id),
        observed_at      TIMESTAMPTZ NOT NULL,
        account_label    TEXT,
        reservation_id   TEXT,
        ship_code        TEXT,
        sail_date        TEXT,
        nights           INTEGER,
        item_kind        TEXT NOT NULL,
        item_code        TEXT,
        item_name        TEXT,
        guest_id         TEXT,
        guest_name       TEXT,
        paid_price       NUMERIC(12,2),
        current_price    NUMERIC(12,2),
        currency         TEXT,
        per_night        INTEGER NOT NULL DEFAULT 0,
        discount_applied TEXT,
        status           TEXT NOT NULL,
        rebook_decision  TEXT,
        notified         INTEGER NOT NULL DEFAULT 0,
        order_date       TEXT,
        ship_name        TEXT,
        cabin_label      TEXT
    );
    CREATE INDEX IF NOT EXISTS idx_price_points_latest
        ON price_points (reservation_id, item_code, guest_id, observed_at DESC);
    CREATE INDEX IF NOT EXISTS idx_price_points_history
        ON price_points (item_code, sail_date, observed_at);
    CREATE INDEX IF NOT EXISTS idx_price_points_run
        ON price_points (run_id);

    CREATE TABLE IF NOT EXISTS bookings (
        id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        run_id           BIGINT NOT NULL REFERENCES runs(run_id),
        observed_at      TIMESTAMPTZ NOT NULL,
        account_label    TEXT,
        reservation_id   TEXT NOT NULL,
        ship_code        TEXT,
        ship_name        TEXT,
        sail_date        TEXT,
        nights           INTEGER,
        stateroom_type   TEXT,
        stateroom_number TEXT,
        stateroom_category TEXT,
        guest_count      INTEGER,
        guests_json      TEXT,
        loyalty_tier     TEXT,
        loyalty_points   INTEGER,
        checkin_label    TEXT,
        final_payment_date TEXT,
        past_final_payment INTEGER,
        balance_due      INTEGER,
        booking_currency TEXT,
        friendly_name    TEXT
    );
    CREATE INDEX IF NOT EXISTS idx_bookings_latest ON bookings (reservation_id, observed_at DESC);

    CREATE TABLE IF NOT EXISTS promos (
        id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        run_id           BIGINT NOT NULL REFERENCES runs(run_id),
        observed_at      TIMESTAMPTZ NOT NULL,
        account_label    TEXT,
        ship_code        TEXT,
        sail_date        TEXT,
        promo_id         TEXT,
        promo_title      TEXT,
        promo_line       TEXT,
        promo_start      TEXT,
        promo_end        TEXT
    );
    CREATE INDEX IF NOT EXISTS idx_promos_run ON promos (run_id);
    